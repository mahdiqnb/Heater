for ch in "abcdefghijklmnopqrstuvwxyz":
    ART[ch] = ART[ch.upper()]

BLANK = "....."


def glyph(ch):
    rows = ART.get(ch)
    if rows is None:
        rows = [BLANK] * 7
    assert len(rows) == 7 and all(len(r) == 5 for r in rows), ch
    out = []
    for r in rows:
        v = 0
        for c, p in enumerate(r):
            if p == "#":
                v |= 1 << (4 - c)
        out.append(v)
    return out


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    path = os.path.join(here, "..", "Core", "Inc", "font5x7.h")
    lines = [
        "#ifndef FONT5X7_H",
        "#define FONT5X7_H",
        "#include <stdint.h>",
        "",
        "/* 5x7 bitmap font, printable ASCII 32..126, one byte per row,",
        "   bit 4 = left-most pixel.  Generated by tools/make_font.py. */",
        "static const uint8_t font5x7[95][7] = {",
    ]
    for code in range(32, 127):
        g = glyph(chr(code))
        lines.append("  {0x%02X, 0x%02X, 0x%02X, 0x%02X, 0x%02X, 0x%02X, 0x%02X}, /* %s */"
                     % (*g, (chr(code) if chr(code) != " " else "sp")))
    lines += ["};", "", "#endif", ""]
    open(path, "w", newline="\n").write("\n".join(lines))
    print("wrote", path)


if __name__ == "__main__":
    main()
